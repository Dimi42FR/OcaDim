"""The start-up screen's pictures (gpu/vk/vk_imgui.cpp, drawn by vk_menu.cpp): the logo from assets/branding/ocadim-logo.png and its
backdrop from assets/ocadim-backdrop.png (the player's own artwork, Dimi42FR), as C headers with their pixels, written by
nx2/build.py into the build's own folder (no second copy of the pictures in the repository).

    python nx2/logo_rgba.py [picture.png] [out.h]

Standard library only: the PNG is decoded here (8-bit RGB or RGBA, not interlaced: what the assets are). The backdrop's
header goes beside the logo's (BACKDROP_NAME), RGB and no alpha: three bytes a pixel.
"""
import os
import struct
import sys
import zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SOURCE = os.path.join(ROOT, "assets", "branding", "ocadim-logo.png")
BACKDROP = os.path.join(ROOT, "assets", "ocadim-backdrop.png")
BACKDROP_NAME = "ocadim_backdrop.h"


def decode_rows(data):
    """(width, height, bytes a pixel, the rows' bytes) of an 8-bit, non-interlaced RGBA or RGB PNG"""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    at, idat, head = 8, b"", None
    while at < len(data):
        n, kind = struct.unpack(">I4s", data[at:at + 8])
        body = data[at + 8:at + 8 + n]
        if kind == b"IHDR":
            head = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
        at += 12 + n
    w, h, depth, colour, _, _, interlace = head
    if depth != 8 or colour not in (2, 6) or interlace:
        raise ValueError("only 8-bit RGB/RGBA, not interlaced: %r" % (head,))
    bpp = 4 if colour == 6 else 3
    raw, stride = zlib.decompress(idat), w * bpp
    out, prev = bytearray(), bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + ((a + b) >> 1)) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        prev = line
        out += line
    return w, h, bpp, bytes(out)


def decode(data):
    """(width, height, RGBA bytes) of an 8-bit, non-interlaced RGBA or RGB PNG"""
    w, h, bpp, px = decode_rows(data)
    if bpp == 4:
        return w, h, px
    out = bytearray(w * h * 4)
    out[0::4], out[1::4], out[2::4], out[3::4] = px[0::3], px[1::3], px[2::3], b"\xff" * (w * h)
    return w, h, bytes(out)


def array(name, px, wraps=32):
    """The bytes as a C array's lines"""
    lines = ["static const unsigned char %s[%d] = {" % (name, len(px))]
    for i in range(0, len(px), wraps):
        lines.append(",".join(str(b) for b in px[i:i + wraps]) + ",")
    lines.append("};")
    return lines


def header(png_path=SOURCE):
    if not os.path.isfile(png_path):   # (a source tree without the picture: the screen shows the wordmark alone)
        return "// generated by nx2/logo_rgba.py: no assets/branding/ocadim-logo.png\n#pragma once\n"
    w, h, px = decode(open(png_path, "rb").read())
    lines = ["// generated by nx2/logo_rgba.py from assets/branding/ocadim-logo.png: do not edit",
             "#pragma once",
             "#define LONGSHOT_LOGO 1",
             "static const unsigned longshot_logo_w = %d, longshot_logo_h = %d;" % (w, h)]
    lines += array("longshot_logo_rgba", px)
    return "\n".join(lines) + "\n"


def backdrop_header(png_path=BACKDROP):
    """The start-up screen's backdrop (vk_menu.cpp draw_startup): the player's own artwork, Dimi42FR, RGB and no alpha"""
    if not os.path.isfile(png_path):
        return "// generated by nx2/logo_rgba.py: no assets/ocadim-backdrop.png\n#pragma once\n"
    w, h, bpp, px = decode_rows(open(png_path, "rb").read())
    if bpp == 4:   # (the picture has no alpha: RGB only, a quarter less to compile)
        rgb = bytearray(w * h * 3)
        rgb[0::3], rgb[1::3], rgb[2::3] = px[0::4], px[1::4], px[2::4]
        px = bytes(rgb)
    lines = ["// generated by nx2/logo_rgba.py from assets/ocadim-backdrop.png (the player's own artwork, Dimi42FR): do not edit",
             "#pragma once",
             "#define LONGSHOT_BACKDROP 1",
             "static const unsigned longshot_backdrop_w = %d, longshot_backdrop_h = %d;" % (w, h)]
    lines += array("longshot_backdrop_rgb", px)
    return "\n".join(lines) + "\n"


def emit(out_path, text):
    """Writes a header when it differs (an unchanged one keeps its timestamp)"""
    try:
        with open(out_path, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write(out_path, png_path=SOURCE):
    """Writes the logo's header at out_path and the backdrop's beside it; returns both their texts"""
    text = header(png_path)
    emit(out_path, text)
    backdrop = backdrop_header()
    emit(os.path.join(os.path.dirname(out_path), BACKDROP_NAME), backdrop)
    return text + backdrop


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    out = sys.argv[2] if len(sys.argv) > 2 else "longshot_logo.h"
    write(out, src)
    print("logo_rgba: %s, and %s beside it" % (out, BACKDROP_NAME))
